import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source=readFileSync(new URL('../crop-circle-engine.js',import.meta.url),'utf8');
const html=readFileSync(new URL('../crop-circles.html',import.meta.url),'utf8');
const sandbox={window:{}};
new vm.Script(source,{filename:'crop-circle-engine.js'}).runInNewContext(sandbox);
const E=sandbox.window.PhiCropCircle;
const raw=E.parseAngles('105, 35, 145,35,180\n325,70,215,180,145');
assert.equal(raw.length,10);
assert.equal(raw.reduce((a,b)=>a+b,0),1435);
assert.equal(E.decode(raw,36).sequence,'3141592654');
assert.equal(E.decode(raw,36).reading,'3.141592654');
assert.ok(Math.abs(E.decode(raw,36).rmse-Math.sqrt(19/10))<1e-9);
assert.equal(E.decode(raw,36).candidates[0].name,'π (rounded)');
assert.equal(E.decode(raw,36).candidates[0].full,true);
assert.ok(E.scanUnits(raw).some(row=>row.unit===36));
assert.equal(E.decode([359,36],36).valid,false);
assert.throws(()=>E.parseAngles('35, NaN'));
assert.throws(()=>E.parseAngles('0, 35'));
assert.throws(()=>E.parseAngles('361, 35'));
assert.throws(()=>E.parseAngles('35'));
assert.throws(()=>E.decode([35,36],0));
const centre={x:100,y:100};
const dirs=E.traceAngles(centre,[{x:200,y:100},{x:100,y:200},{x:0,y:100}],'clockwise');
assert.equal(dirs.map(Math.round).join(','),'90,90');
const reverse=E.traceAngles(centre,[{x:200,y:100},{x:100,y:200}],'counterclockwise');
assert.ok(Math.abs(reverse[0]-270)<1e-9);
const s1=E.simulatePi(raw,{seed:369,trials:100});
const s2=E.simulatePi(raw,{seed:369,trials:100});
assert.equal(JSON.stringify(s1),JSON.stringify(s2),'null simulation must be reproducible');
assert.throws(()=>E.simulatePi([20,30]));
assert.match(html,/<canvas id="stage"/);
assert.match(html,/id="imageFile"/);
assert.match(html,/id="export"/);
assert.match(html,/src="crop-circle-engine.js"/);
const inline=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].filter(x=>x[1].trim());
assert.equal(inline.length,1);
new vm.Script(inline[0][1],{filename:'crop-circles-inline.js'});
console.log('PASS: crop-circle angle decoding, controls, photo-trace bearings, validation, simulation determinism, HTML JS syntax.');
