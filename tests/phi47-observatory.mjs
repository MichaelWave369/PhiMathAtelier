import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const js=readFileSync(new URL('../phi47-observatory.js',import.meta.url),'utf8');
const html=readFileSync(new URL('../phi47-observatory.html',import.meta.url),'utf8');
new vm.Script(js,{filename:'phi47-observatory.js'});
const sandbox={module:{exports:{}}};
new vm.Script(js).runInNewContext(sandbox);
const F=sandbox.module.exports;
assert.equal(F.N,47);
assert.equal(F.state(369).reduce((s,v)=>s+v,0),1);
assert.equal(F.graph().length,47);
assert.ok(F.graph().every(neighbors=>neighbors.length===8));
assert.equal(F.inspect(0,false).activeTeeth,0);
assert.equal(F.inspect(0,true).activeTeeth,9);
assert.deepEqual(JSON.parse(JSON.stringify(F.inspect(12))),JSON.parse(JSON.stringify(F.inspect(12))));
const records=F.sweep();
assert.equal(records.length,47);
assert.ok(new Set(records.map(r=>r.interfaceCorrelation)).size>1);
assert.ok(records.every(r=>r.initialA===1&&r.initialB===1&&r.origin==='SIMULATED'&&r.authority==='NONE'));
assert.throws(()=>F.inspect(47,true),/Invalid/);
assert.throws(()=>F.graph([8,9,12,39]),/Colliding/);
for(const id of ['mesh','shift','mode','topology','stats','export'])assert.ok(html.includes('id="'+id+'"'));
assert.ok(html.includes('phi47-observatory.js') && html.includes('SIMULATED'));
assert.ok(!/fetch\(|XMLHttpRequest/.test(js));
console.log('PASS: Φ47 independent offline observatory, controls, 47-step sweep, privacy and simulation labeling.');
